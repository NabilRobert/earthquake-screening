"""Save the trained model with its hash, and write slice 2's result as Markdown, judged by the fixed pass rule."""

import hashlib
import pickle
from pathlib import Path

import numpy as np

from earthquake_screening.buildings.experiment import (
    CONFIDENCE_LEVEL,
    COVERAGE_BAND,
    Accuracy,
    BuildingModel,
    ExperimentResult,
    has_passed,
)


def save_model(model: BuildingModel, path: Path) -> str:
    """Pickle the model and return its SHA-256 (M5). Only this repo's own files are ever unpickled."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(pickle.dumps(model))
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _percent(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def _row(label: str, accuracy: Accuracy) -> str:
    factor = "n/a" if accuracy.median_interval_factor is None else f"{accuracy.median_interval_factor:.2f}"
    return (
        f"| {label} | {accuracy.rows:,} | {accuracy.rmse_ln:.3f} | {_percent(accuracy.median_relative_error)} | "
        f"{_percent(accuracy.within_factor_1_5)} | {_percent(accuracy.within_factor_2)} | "
        f"{_percent(accuracy.coverage)} | {factor} |"
    )


TABLE_HEADER = (
    "| Rows | Count | RMSE of ln drift | Median error | Within factor 1.5 | Within factor 2 | 90% coverage "
    "| Median interval factor |\n"
    "|---|---|---|---|---|---|---|---|"
)


def _accuracy_tables(result: ExperimentResult) -> list[str]:
    evaluation = result.evaluation
    accepted = (
        [] if evaluation.accepted_test is None else [_row("Test, accepted by the envelope", evaluation.accepted_test)]
    )
    return [
        TABLE_HEADER,
        _row(f"**Test (judged): {result.chosen}**", evaluation.test),
        _row("Test (judged): class baseline", evaluation.baseline_test),
        _row(f"Test, known shaking: {result.chosen}", evaluation.known_shaking),
        _row("Test, known shaking: class baseline", evaluation.baseline_known_shaking),
        *accepted,
        "",
        "**By storey count (judged test rows):**",
        "",
        TABLE_HEADER,
        *(_row(f"{storeys} storeys", accuracy) for storeys, accuracy in sorted(evaluation.test_by_storeys.items())),
    ]


def format_report(result: ExperimentResult, model_sha256: str, run_minutes: float) -> str:
    split, evaluation = result.split, result.evaluation
    verdict = "PASS" if has_passed(result) else "MISS"
    coverage_band = f"{100 * COVERAGE_BAND[0]:.0f}-{100 * COVERAGE_BAND[1]:.0f}%"
    scores = ", ".join(f"{name} {np.mean(values):.3f}" for name, values in result.cross_validation.items())
    lines = [
        "# Slice 2 result: building surrogate on PRJ-2048",
        "",
        "Generated by `earthquake-screening train-buildings`. The pass rule is in [prj2048.md](prj2048.md).",
        "",
        f"## Verdict: {verdict}",
        "",
        f"- Split clean (no frame or held-out ground motion leaks): **{result.is_split_clean}**",
        f"- {100 * CONFIDENCE_LEVEL:.0f}% interval coverage on test: **{_percent(evaluation.test.coverage)}** "
        f"(band {coverage_band})",
        f"- RMSE of ln drift on test: **{evaluation.test.rmse_ln:.3f}** against the class baseline's "
        f"**{evaluation.baseline_test.rmse_ln:.3f}**",
        "",
        "## Accuracy against the full simulation",
        "",
        *_accuracy_tables(result),
        "",
        "## The run",
        "",
        f"- Frames: {split.fit_frames.size} fit, {split.calibration_frames.size} calibration, "
        f"{split.test_frames.size} test. Ground motions: {split.training_motions.size} training, "
        f"{split.held_out_motions.size} held out.",
        f"- Cross-validation on the fit rows, mean RMSE of ln drift: {scores}. Chosen: **{result.chosen}**.",
        f"- Test rows the envelope would refuse: {_percent(evaluation.refusal_rate)}.",
        f"- Time per screen (envelope check and prediction, one row): {1000 * evaluation.seconds_per_screen:.1f} ms.",
        f"- Whole run: {run_minutes:.1f} min on the laptop, $0.",
        f"- Model file SHA-256: `{model_sha256}`.",
    ]
    return "\n".join(lines) + "\n"
